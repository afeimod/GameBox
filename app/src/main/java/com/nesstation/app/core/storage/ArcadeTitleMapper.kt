    /**
     * 已知的版本后缀 → 友好提示（用于未在主表中找到的驱动名）。
     *
     * 例如 kof98h.zip 中的 "h" 代表 "Hack" 修订版，
     * 我们尝试先去掉后缀再查表。
     */
    private val REVISION_SUFFIXES = listOf(
        "h" to " - 改版",
        "u" to " - 美版",
        "j" to " - 日版",
        "e" to " - 欧版",
        "a" to " - 亚洲版",
        "k" to " - 韩版",
        "p" to " - Plus",
