        "ch" to " - 中文改版",
        "sp" to " - 特殊版",
        "m" to " - 修正版",
        "x" to " - 魔改版",
        "s" to " - Super"
    )

    /**
     * 根据驱动名查找游戏中文名。
     *
     * 查找策略：
     *   1) 精确匹配（不区分大小写）
     *   2) 去除常见后缀（h/u/j/e/a/k/p/r1/r2/b/o/bl/t/c/ch/sp/m/x）后再匹配
     *   3) 仍找不到 → 返回 null（调用方使用原驱动名）
     *
     * @param driverName zip 文件名（不含 .zip 后缀），如 "kof98h" / "mvc"
     * @return 中文名称，如 "拳皇98 - 梦之终结未圆满"；找不到返回 null
     */
    fun lookup(driverName: String?): String? {
        if (driverName.isNullOrBlank()) return null
        val key = driverName.trim().lowercase()

        // 1) 精确匹配
        DRIVER_TO_CN[key]?.let { return it }

        // 2) 去除版本后缀再匹配
        //    例如 "kof98h" → 去掉 "h" → "kof98" → "拳皇98 - ..."
        for ((suffix, label) in REVISION_SUFFIXES) {
            if (key.endsWith(suffix) && key.length > suffix.length + 2) {
                val base = key.removeSuffix(suffix)
                DRIVER_TO_CN[base]?.let { cn ->
                    // 如果主表里已经有带后缀的精确条目，会优先返回（已处理）
                    // 这里仅追加修饰
                    return if (cn.contains(" - ")) "$cn ($label)" else "$cn$label"
                }
            }
        }

        // 3) 尝试去掉末尾的数字（"mvc2" → "mvc"），再查一次
        val strippedTrailingDigit = key.replace(Regex("\\d+$"), "")
        if (strippedTrailingDigit.length >= 2 && strippedTrailingDigit != key) {
            DRIVER_TO_CN[strippedTrailingDigit]?.let { return it }
        }

        return null
    }

    /**
     * 解析完整的 zip 文件名（含扩展名）→ 中文名。
     * 兼容 .zip / .7z / 大写扩展名。
     *
     * @param fileName 例如 "kof98h.zip"、"Mvc.7z"、"UNKNOWN_FILE.ZIP"
     * @return 中文名，找不到时返回 null（调用方应回退到 fileName 去扩展名）
     */
    fun lookupByFileName(fileName: String?): String? {
        if (fileName.isNullOrBlank()) return null
        val lower = fileName.lowercase()
        val driverName = when {
            lower.endsWith(".zip") -> fileName.removeSuffix(".zip").removeSuffix(".ZIP")
            lower.endsWith(".7z") -> fileName.removeSuffix(".7z").removeSuffix(".7Z")
            else -> fileName.substringBeforeLast('.', fileName)
        }
        return lookup(driverName)
    }

    /**
     * 给定原始文件名，返回最适合显示的标题：
     *   - 优先使用中文名
     *   - 找不到则使用驱动名（去扩展名）
     *
     * 用于 RomStore.add 入口的便捷包装。
     */
    fun resolveDisplayTitle(fileName: String?): String {
        return lookupByFileName(fileName) ?: fileName?.substringBeforeLast('.') ?: "未知游戏"
    }
